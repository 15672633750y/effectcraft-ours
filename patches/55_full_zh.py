def main() -> None:
    root = Path(os.environ["EFFECTCRAFT_DIR"]).resolve()
    path = root / "crates/ui-egui/src/i18n/ui.rs"
    src = path.read_text(encoding="utf-8")
    if MARKER in src:
        print("extra Chinese entries already installed")
        return
    if src.count(ANCHOR) != 1:
        raise SystemExit("catalog anchor missing")
    src = src.replace(ANCHOR, ANCHOR + "    // " + MARKER + "\n" + ROWS, 1)
    path.write_text(src, encoding="utf-8")
    print("added %d Chinese entries" % len(ROWS.strip().splitlines()))


if __name__ == "__main__":
    main()
